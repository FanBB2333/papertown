// Builds design/index.html (gallery) and design/prototype.html as self-contained offline
// pages, and exports the sprite library to assets/ in the paper-craft palette.
//
//   node design/build.mjs

import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, THEME_ORDER, resolveSVG } from './src/theme.js';
import { BUILDINGS, PROPS, ITEMS, WORKERS, DISTRICTS, TW, TH, ZU, spriteSVG, propSVG, workerBody } from './src/sprites.js';
import { PLACEMENTS } from './src/world.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = f => readFile(join(here, 'src', f), 'utf8');

const strip = s => s.replace(/^import .*$/gm, '');
const css = await src('style.css');
const template = await src('template.html');
const PAGES = [
  ['index.html', 'Papertown 设计方案', 'gallery.js'],
  ['prototype.html', 'Papertown 原型', 'proto.js'],
];
for (const [file, title, entry] of PAGES) {
  let js = '';
  for (const f of ['theme.js', 'sprites.js', 'sample.js', 'world.js', 'layouts.js', entry]) js += `\n// ---- ${f} ----\n${strip(await src(f))}`;
  const html = template
    .replace('__TITLE__', () => title)
    .replace('/*__CSS__*/', () => css)
    .replace('/*__JS__*/', () => js);
  await writeFile(join(here, file), html);
}

const T = THEMES.paper;
const out = join(root, 'assets');
await rm(join(out, 'sprites'), { recursive: true, force: true });
for (const d of ['buildings', 'props', 'items', 'workers']) await mkdir(join(out, 'sprites', d), { recursive: true });

const FONT = 'font-family="PingFang SC, Hiragino Sans GB, Helvetica, Arial, sans-serif" font-weight="700"';
const standalone = (vb, w, h, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${Math.round(w)}" height="${Math.round(h)}" ${FONT}>${body}</svg>\n`;

const manifest = {
  note: 'Generated by design/build.mjs from design/src/sprites.js. Colours are the paper-craft palette; other styles live in themes.',
  grid: { tileWidth: TW, tileHeight: TH, heightUnit: ZU, origin: 'sprite (0,0) is the back corner of the footprint' },
  districts: DISTRICTS,
  buildings: [], props: [], items: [], workers: [],
  placements: PLACEMENTS,
  themes: Object.fromEntries(THEME_ORDER.map(k => [k, { name: THEMES[k].name, en: THEMES[k].en, ui: THEMES[k].ui, materials: THEMES[k].mats }])),
};

for (const [type, b] of Object.entries(BUILDINGS)) {
  const s = spriteSVG(type);
  const file = `assets/sprites/buildings/${type}.svg`;
  await writeFile(join(root, file), standalone(s.vb, s.w, s.h, resolveSVG(s.body, b.accent, T)));
  manifest.buildings.push({ type, name: b.name, en: b.en, district: b.district, footprint: [b.w, b.d], height: b.h, accent: b.accent, represents: b.rep, tech: b.tech, later: !!b.later, file });
}
for (const [key, pr] of Object.entries(PROPS)) {
  const s = propSVG(key);
  const file = `assets/sprites/props/${key}.svg`;
  await writeFile(join(root, file), standalone(s.vb, s.w, s.h, resolveSVG(s.body, '#c47a3a', T)));
  manifest.props.push({ key, name: pr.name, footprint: [pr.w, pr.d], file });
}
for (const [key, it] of Object.entries(ITEMS)) {
  const file = `assets/sprites/items/${key}.svg`;
  await writeFile(join(root, file), standalone('0 0 48 48', 96, 96, resolveSVG(`<g class="sp">${it.svg}</g>`, it.accent, T)));
  manifest.items.push({ key, name: it.name, represents: it.rep, accent: it.accent, file });
}
for (const [key, w] of Object.entries(WORKERS)) {
  const file = `assets/sprites/workers/${key}.svg`;
  await writeFile(join(root, file), standalone('0 0 48 48', 96, 96, resolveSVG(`<g class="sp">${workerBody(key)}</g>`, w.accent, T)));
  manifest.workers.push({ key, name: w.name, role: w.rep, accent: w.accent, file });
}
await writeFile(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

const row = cells => `| ${cells.join(' | ')} |`;
const md = [
  '# Papertown 素材',
  '',
  '这里的 SVG 全部由 `design/src/sprites.js` 用代码生成，配色是纸艺风格（Paper-craft），没有引用任何第三方素材。',
  '改素材请改源码，然后运行 `node design/build.mjs` 重新导出；不要手改这里的文件。',
  '',
  '- 等距网格：瓦片 64×32 像素，高度 1 单位 = 26 像素；每个建筑 SVG 的坐标原点是占地的后角。',
  '- `manifest.json`：建筑 type → 文件、占地、强调色、代表含义；世界地图的摆放（placements）；四种风格的完整色板。',
  '- 正式开发时，前端按 `type` 查 manifest 取图，换画风或换成 3D 模型时只换映射，不动业务逻辑。',
  '',
  '## 建筑',
  '',
  row(['type', '名称', '区域', '占地', '代表', '技术']), row(['---', '---', '---', '---', '---', '---']),
  ...manifest.buildings.map(b => row([`\`${b.type}\``, b.name + (b.later ? '（以后再做）' : ''), DISTRICTS[b.district].name, `${b.footprint[0]}×${b.footprint[1]}`, b.represents, b.tech])),
  '',
  '## 物件',
  '',
  row(['key', '名称', '代表']), row(['---', '---', '---']),
  ...manifest.items.map(i => row([`\`${i.key}\``, i.name, i.represents])),
  '',
  '## 员工',
  '',
  row(['key', '角色', '职责']), row(['---', '---', '---']),
  ...manifest.workers.map(w => row([`\`${w.key}\``, w.name, w.role])),
  '',
  '## 地形与道具',
  '',
  row(['key', '名称']), row(['---', '---']),
  ...manifest.props.map(p => row([`\`${p.key}\``, p.name])),
  '',
].join('\n');
await writeFile(join(out, 'README.md'), md);

console.log(`index.html and prototype.html written; exported ${manifest.buildings.length} buildings, ${manifest.props.length} props, ${manifest.items.length} items, ${manifest.workers.length} workers`);
